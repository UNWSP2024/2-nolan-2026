# Average Age

def average_age():
    # Get User Input
    age1 = 18
    age2 = 20
    age3 = 21
    age4 = 19
    age5 = 25

    # Sum ages
    age_sum = age1 + age2 + age3 + age4 + age5
    # Average the ages
    average = age_sum / 5
    # Print the results
    print(average)
# Line which calls the above function.
average_age()
