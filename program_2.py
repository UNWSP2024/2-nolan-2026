def average_age():
    # Get User Input
    Marco = 18
    James = 20
    Quinn = 21
    Sally = 19
    Jacob = 25

    # Sum ages
    age_sum = Marco + James + Quinn + Sally + Jacob
    # Average the ages
    average = age_sum / 5
    # Print the results
    print(average)
